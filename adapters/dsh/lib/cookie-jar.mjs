/**
 * Cookie parsing only — no HTTP, no transport.
 *
 * A browser hands its cookie jar to `fetch` automatically; a Node CLI has to
 * read one. This module does the smallest thing that covers the ways an
 * operator ends up with a session cookie:
 *
 * - a Netscape `cookies.txt` jar, which is what `curl -c` writes;
 * - a `Cookie:` header line copied from a browser's network panel;
 * - a bare `name=value` line.
 *
 * It deliberately does not validate or decode the value. The Host decides
 * whether a cookie is acceptable; a client that pre-judged it could disagree
 * with the Host and report a different reason for the same 401.
 *
 * @module lib/cookie-jar
 */

/**
 * The prefix `curl` writes on an `HttpOnly` cookie line.
 *
 * A Netscape jar has no column for the `HttpOnly` attribute, so libcurl encodes
 * it in the domain column instead: an `HttpOnly` cookie is written as
 * `#HttpOnly_<domain>\t...`. That leading `#` makes the line *look* like a
 * comment, and a parser that filters `#` lines throws away exactly the cookie
 * that matters — a session cookie is almost always `HttpOnly`, and the CLI's own
 * help text tells operators to create the jar with `curl -c`. So this prefix is
 * a domain marker, not a comment: it is stripped and the rest is parsed
 * normally.
 */
export const HTTP_ONLY_PREFIX = "#HttpOnly_";

/**
 * Whether a jar line is a comment.
 *
 * `#HttpOnly_` lines are not: they are cookies whose domain column carries the
 * attribute. Every other `#` line — the `# Netscape HTTP Cookie File` banner,
 * `# This file was generated by libcurl!`, and anything a user added — is.
 * @param {string} line - one trimmed jar line.
 * @returns {boolean} true when the line carries no cookie.
 */
function isComment(line) {
  if (line.startsWith(HTTP_ONLY_PREFIX)) return false;
  return line.startsWith("#");
}

/**
 * One Netscape jar line's name and value.
 *
 * The columns are `domain, includeSubdomains, path, secure, expiry, name,
 * value`. Taking the last two rather than fixed indices keeps this working for
 * an `#HttpOnly_` line after its prefix is stripped, because stripping the
 * prefix leaves the same seven columns; it also tolerates a domain containing a
 * tab-free variant of any of the leading fields.
 * @param {string} line - one jar line, already trimmed.
 * @returns {{name: string, value: string} | undefined} the pair, or undefined.
 */
function jarPair(line) {
  const columns = line.split("\t");
  if (columns.length < 2) return undefined;
  const name = (columns[columns.length - 2] ?? "").trim();
  const value = (columns[columns.length - 1] ?? "").trim();
  if (name === "" || value === "") return undefined;
  return { name, value };
}

/**
 * Extract the DSH session cookie from one of the accepted text shapes.
 *
 * Netscape jars and header lines can carry several cookies; the Host's session
 * cookie is the one whose name starts with `dsh-auth-`, so that is what is
 * selected when present. A bare `name=value` line is taken as-is.
 * @param {string} text - the file or stdin contents.
 * @returns {string} the `Cookie` header value, or an empty string when none was found.
 */
export function parseCookieText(text) {
  // Split the raw text rather than a trimmed copy: trimming the whole file eats
  // a trailing empty column, and a jar line whose value column is empty would
  // then be read as a different cookie (`0=dsh-auth-empty`) instead of as no
  // cookie at all. Only the carriage return is stripped, so column boundaries
  // survive.
  const lines = String(text ?? "")
    .split(/\r?\n/)
    .map((line) => line.replace(/\r$/, ""));
  if (lines.every((line) => line.trim() === "")) return "";

  // Netscape jar lines are tab-separated with the name/value in the last two
  // columns. `#HttpOnly_` lines are cookies, not comments, so their prefix is
  // stripped first and the remainder parsed as the same seven columns.
  const pairs = lines
    .filter((line) => line.trim() !== "" && !isComment(line.trim()))
    .map((line) => (line.startsWith(HTTP_ONLY_PREFIX) ? line.slice(HTTP_ONLY_PREFIX.length) : line))
    .filter((line) => line.includes("\t"))
    .map(jarPair)
    .filter((pair) => pair !== undefined);

  if (pairs.length > 0) {
    const session = pairs.filter((pair) => pair.name.startsWith("dsh-auth-"));
    const chosen = session.length > 0 ? session : pairs;
    return chosen.map((pair) => `${pair.name}=${pair.value}`).join("; ");
  }

  // A `Cookie:` header line, or a bare name=value pair. Comments are skipped
  // rather than returned: a jar of nothing but comments must read as "no
  // credential", not as a credential whose value is the file's banner. A
  // tab-bearing line is a jar line whose columns did not yield a pair (an empty
  // value, say), and must not be handed back as if it were a bare pair.
  const first = lines
    .map((line) => line.trim())
    .find((line) => line !== "" && !isComment(line) && !line.includes("\t"));
  if (first === undefined) return "";
  return first.replace(/^cookie:\s*/i, "").trim();
}

/**
 * Whether a parsed credential looks like a DSH session cookie.
 *
 * Only a shape check: an empty or unrelated value is caught here so the caller
 * can report "no credential" instead of sending an empty header and surfacing a
 * 401 the operator cannot act on.
 * @param {string} value - the parsed cookie header value.
 * @returns {boolean} true when there is a session cookie to send.
 */
export function looksLikeSessionCookie(value) {
  return typeof value === "string" && /(^|;\s*)dsh-auth-[^=\s]+=\S/.test(value);
}
