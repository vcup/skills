/**
 * Tests for the cookie jar parser.
 *
 * The case that matters most is the one a user hits first: the CLI's own help
 * text says to create the jar with `curl -c`, and `curl` writes an `HttpOnly`
 * cookie as `#HttpOnly_<domain>\t...`. That leading `#` made the old parser
 * treat the line as a comment and discard the only credential in the file, so a
 * perfectly valid session reported "no credential" (exit 3). These tests are
 * built around real jar text, including a jar captured from `curl` itself.
 *
 * The second property is that a jar containing *only* comments reads as "no
 * credential" rather than as a credential whose value is the file's banner — the
 * old fallback returned `"# Netscape HTTP Cookie File"`, which is not a cookie
 * and would have been sent as one.
 */

import { afterAll, describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { HTTP_ONLY_PREFIX, looksLikeSessionCookie, parseCookieText } from "./lib/cookie-jar.mjs";

/** The exact bytes `curl -c jar.txt` writes for an `HttpOnly` session cookie. */
const CURL_HTTP_ONLY_JAR = [
  "# Netscape HTTP Cookie File",
  "# https://curl.se/docs/cookies.html",
  "# This file was generated by libcurl! Edit at your own risk.",
  "",
  "#HttpOnly_127.0.0.1\tFALSE\t/\tFALSE\t0\tdsh-auth-abc123\tsecretvalue",
  "",
].join("\n");

const roots: string[] = [];

afterAll(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe("a curl -c jar", () => {
  test("an #HttpOnly_ line is a cookie, not a comment", () => {
    const parsed = parseCookieText(CURL_HTTP_ONLY_JAR);
    expect(parsed).toBe("dsh-auth-abc123=secretvalue");
    expect(looksLikeSessionCookie(parsed)).toBe(true);
  });

  test("the prefix is stripped, so the name and value are still the last two columns", () => {
    // Seven columns before stripping, seven after: stripping only the domain
    // prefix must not shift which columns hold the name and the value.
    const line = `${HTTP_ONLY_PREFIX}example.test\tFALSE\t/\tFALSE\t0\tdsh-auth-x\tv`;
    expect(parseCookieText(line)).toBe("dsh-auth-x=v");
  });

  test("a real jar file on disk parses the same way", () => {
    const root = mkdtempSync(join(tmpdir(), "cookie-jar-"));
    roots.push(root);
    const path = join(root, "jar.txt");
    writeFileSync(path, CURL_HTTP_ONLY_JAR);
    expect(parseCookieText(readFileSync(path, "utf8"))).toBe("dsh-auth-abc123=secretvalue");
  });
});

describe("other accepted shapes", () => {
  test("a plain Netscape jar without the prefix is still found", () => {
    const text = "# Netscape HTTP Cookie File\n127.0.0.1\tFALSE\t/\tFALSE\t0\tdsh-auth-plain\tval2\n";
    expect(parseCookieText(text)).toBe("dsh-auth-plain=val2");
  });

  test("a Cookie: header line is still found", () => {
    expect(parseCookieText("Cookie: dsh-auth-hdr=abc123; other=x\n")).toBe("dsh-auth-hdr=abc123; other=x");
  });

  test("a bare name=value line is still found", () => {
    expect(parseCookieText("dsh-auth-bare=zzz\n")).toBe("dsh-auth-bare=zzz");
  });

  test("a jar with several cookies prefers the session cookie", () => {
    const text = [
      "# Netscape HTTP Cookie File",
      "#HttpOnly_127.0.0.1\tFALSE\t/\tFALSE\t0\tunrelated\tone",
      "#HttpOnly_127.0.0.1\tFALSE\t/\tFALSE\t0\tdsh-auth-real\ttwo",
    ].join("\n");
    expect(parseCookieText(text)).toBe("dsh-auth-real=two");
  });
});

describe("no credential", () => {
  test("a jar of only real comments is 'no credential', not a banner credential", () => {
    const text = "# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# generated by libcurl\n";
    expect(parseCookieText(text)).toBe("");
    expect(looksLikeSessionCookie("")).toBe(false);
  });

  test("empty and whitespace-only input is 'no credential'", () => {
    expect(parseCookieText("")).toBe("");
    expect(parseCookieText("   \n\t\n")).toBe("");
    expect(parseCookieText(undefined)).toBe("");
  });

  test("a jar whose only line has an empty value is 'no credential'", () => {
    expect(parseCookieText("127.0.0.1\tFALSE\t/\tFALSE\t0\tdsh-auth-empty\t\n")).toBe("");
  });
});
