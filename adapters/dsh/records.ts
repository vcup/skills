/**
 * The v1 archive tree: what a commit contains, and how it is read back.
 *
 * `OPERATIONS.md` §3 fixes the layout, and this module is the only place that
 * knows it. Two properties matter and are easy to lose:
 *
 * - **No self-reference.** A record must not contain the hash of the commit that
 *   contains it, because that hash does not exist until after the tree is
 *   written. Records therefore carry their own `object_revision` and the
 *   sequence they were created or updated at, and the commit hash is derived by
 *   whoever reads the ref.
 * - **Deterministic bytes.** The same logical archive state must produce the
 *   same tree, so a re-run after a crash cannot produce a second, different
 *   commit for the same revision. Keys are written in a fixed order and JSON is
 *   emitted with a fixed shape.
 *
 * Everything here is pure: it builds and parses the bytes, and the Archive seam
 * writes them. That split is what lets the layout be tested without Git.
 *
 * @module adapters/dsh/records
 */

import { createHash } from "node:crypto";

/** The format this module reads and writes. Unknown formats are refused. */
export const ARCHIVE_FORMAT = "ensemble-archive/v1";

/** The single business ref the archive publishes. */
export const ARCHIVE_REF = "refs/ensemble/main";

/** Kinds of record the v1 tree holds. Closed set: an unknown kind is refused. */
export const RECORD_KINDS = ["checkpoint", "artifact", "contribution", "reflection", "lesson"] as const;

/** One record kind. */
export type RecordKind = (typeof RECORD_KINDS)[number];

/** The source a project is bound to, as the owner confirmed it. */
export interface SourceBinding {
  /** Deployment-owned identity of the execution world the source lives in. */
  readonly worldIdentity: string;
  /** Canonical address of the source inside that world. */
  readonly canonicalAddress: string;
  /** Native workspace reference, opaque to this code. */
  readonly nativeWorkspaceRef: string;
  /** Native session reference, when the owner supplied one. */
  readonly nativeSessionRef?: string;
  /** Baseline the owner recorded, when one is available. */
  readonly baseline?: string;
}

/** One grant: who may do what. v1 has exactly one management subject. */
export interface Grant {
  /** Opaque subject id. Never an email, a name, or a claimed role. */
  readonly subjectId: string;
  readonly rights: readonly string[];
}

/** The archive's own metadata, written at initialize and amended by bind. */
export interface ArchiveMeta {
  readonly format: string;
  /** Generated by the program, not supplied by a caller. */
  readonly archiveId: string;
  /** Monotonic commit sequence, incremented once per published commit. */
  readonly sequence: number;
  readonly binding: SourceBinding;
  readonly grants: readonly Grant[];
  /** Renderer identity for views this archive produced. */
  readonly renderer: string;
}

/** One stored object, with the bookkeeping every kind shares. */
export interface RecordEnvelope {
  readonly format: string;
  readonly kind: RecordKind;
  readonly id: string;
  /** Revision of this object, incremented on each update. */
  readonly objectRevision: number;
  readonly createdSequence: number;
  readonly updatedSequence: number;
  /** Kind-specific body; validated by the caller that owns the kind. */
  readonly body: Readonly<Record<string, unknown>>;
}

/** One operation: what was asked, by whom, and what it changed. */
export interface OperationRecord {
  readonly format: string;
  readonly sequence: number;
  /** Actor identity derived from the invocation, never from the request. */
  readonly actor: string;
  readonly action: string;
  /** Digest of the canonical payload, not the payload itself. */
  readonly payloadDigest: string;
  readonly changedIds: readonly string[];
  readonly result: Readonly<Record<string, unknown>>;
}

/** One receipt: the durable answer to a retried operation key. */
export interface ReceiptRecord {
  readonly format: string;
  readonly payloadDigest: string;
  /** The sequence this key first published at. Not a commit hash. */
  readonly sequence: number;
  readonly result: Readonly<Record<string, unknown>>;
}

/** A refusal with a code the caller can branch on. */
export interface ArchiveRefusal {
  readonly ok: false;
  readonly code:
    | "invalid_input"
    | "unknown_format"
    | "unknown_kind"
    | "invalid_path"
    | "payload_too_large";
  readonly reason: string;
}

/** Stable JSON: keys sorted, no insignificant whitespace. */
export function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value) ?? "null";
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([, entry]) => entry !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([key, entry]) => `${JSON.stringify(key)}:${canonicalJson(entry)}`).join(",")}}`;
}

/**
 * SHA-256 of a UTF-8 string, hex.
 *
 * `node:crypto`, not `Bun.CryptoHasher`: the packaged plugin runs under Node in
 * the Host, where `Bun` does not exist. A Bun-only digest would pass every
 * `bun test` run and fail on the first real install, which is the worst place
 * for a difference to appear.
 * @param text - the string to digest.
 * @returns the lowercase hex digest.
 */
export function digestOf(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

/** Path of the archive metadata file. */
export const META_PATH = "meta.json";

/** Path of one record. */
export function recordPath(kind: RecordKind, id: string): string {
  return `records/${kind}/${id}.json`;
}

/** Path of one operation. */
export function operationPath(sequence: number): string {
  return `operations/${sequence}.json`;
}

/** Path of one receipt, keyed by actor and the caller's operation key. */
export function receiptPath(actorKey: string, key: string): string {
  return `receipts/${actorKey}/${key}.json`;
}

/** Ids and keys become path segments, so they must be plain and bounded. */
const SEGMENT = /^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/;

/**
 * Whether a string can be a path segment in the archive tree.
 *
 * Ids and operation keys come from callers, so they are validated before they
 * become paths: a `/`, a `..`, or a leading dot could otherwise address a file
 * outside the intended directory, and an unbounded name could exhaust a path
 * length.
 * @param value - the candidate segment.
 * @returns true when it is safe as one path component.
 */
export function isSafeSegment(value: string): boolean {
  return SEGMENT.test(value) && value !== "." && value !== "..";
}

/** The largest payload an operation may carry inline. */
export const INLINE_INPUT_BYTES = 256 * 1024;

/**
 * Check a source binding before it is stored.
 *
 * The owner supplies these values, but they still have to be structurally
 * sound: an empty world identity would make "same world" unprovable, and an
 * empty canonical address would bind nothing. This is shape validation only —
 * whether the world really is the Host is a deployment question the caller
 * answers.
 * @param binding - the candidate binding.
 * @returns a refusal, or `{ok: true}`.
 */
export function validateBinding(binding: SourceBinding): { ok: true } | ArchiveRefusal {
  for (const [field, value] of [
    ["worldIdentity", binding.worldIdentity],
    ["canonicalAddress", binding.canonicalAddress],
    ["nativeWorkspaceRef", binding.nativeWorkspaceRef],
  ] as const) {
    if (typeof value !== "string" || value.trim() === "") {
      return { ok: false, code: "invalid_input", reason: `source_descriptor.${field} must be a non-empty string` };
    }
  }
  return { ok: true };
}

/**
 * How a binding's execution world relates to the archive's.
 *
 * `same` means the deployment proved both live in one world. `unproven` means
 * the deployment could not show it. There is deliberately no third state
 * meaning "assume same": the design refuses an unproven binding rather than
 * enabling it, because reading a source through the wrong world is exactly the
 * failure this check exists to prevent.
 */
export type WorldRelation = "same" | "unproven";

/**
 * The deployment's statement about its own topology.
 *
 * `archiveWorldIdentity` is how the deployment names the world the archive's
 * Git actually runs in — a name it chose, not a path string derived from a
 * Session. `sourceWorlds` maps a source's declared `worldIdentity` to whether
 * the deployment has evidence that it is the same world as the archive's.
 *
 * An absent entry is `unproven`, not `same`: an undeclared source is refused
 * rather than assumed, so adding a source cannot silently widen coverage.
 */
export interface TopologyDeclaration {
  readonly archiveWorldIdentity: string;
  readonly sourceWorlds?: Readonly<Record<string, boolean>>;
}

/**
 * Decide whether a source may be bound, given the deployment's topology.
 *
 * Two independent failures, both refused:
 * - the source claims a different world than the archive's;
 * - the deployment has not evidenced that the two worlds are the same.
 *
 * Neither a path that contains the other nor a path that does not is evidence:
 * the design is explicit that same-world is a deployment fact, and that a
 * string comparison must not stand in for it. So this reads a declaration
 * rather than inferring from paths.
 * @param binding - the source being bound.
 * @param topology - the deployment's declared topology.
 * @returns `same` only when the deployment proved it; otherwise `unproven` with
 *   a reason naming which check failed.
 */
export function judgeWorld(
  binding: SourceBinding,
  topology: TopologyDeclaration | undefined,
): { readonly relation: "same" } | { readonly relation: "unproven"; readonly reason: string } {
  if (topology === undefined || topology.archiveWorldIdentity.trim() === "") {
    return {
      relation: "unproven",
      reason:
        "the deployment has not declared which execution world this archive runs in, so the source's world cannot be compared with it",
    };
  }
  if (binding.worldIdentity !== topology.archiveWorldIdentity) {
    return {
      relation: "unproven",
      reason:
        `the source declares world ${JSON.stringify(binding.worldIdentity)} but the archive runs in ` +
        `${JSON.stringify(topology.archiveWorldIdentity)}; a cross-world source is not supported`,
    };
  }
  if (topology.sourceWorlds?.[binding.worldIdentity] !== true) {
    return {
      relation: "unproven",
      reason:
        `the deployment has not evidenced that ${JSON.stringify(binding.worldIdentity)} is the same execution world as ` +
        "the archive; refusing to enable this binding on an unproven topology",
    };
  }
  return { relation: "same" };
}

/** Whether a grant list names at least one subject with at least one right. */
export function validateGrants(grants: readonly Grant[]): { ok: true } | ArchiveRefusal {
  if (grants.length === 0) {
    return { ok: false, code: "invalid_input", reason: "initial_grants must name at least one management subject" };
  }
  for (const grant of grants) {
    if (!isSafeSegment(grant.subjectId)) {
      return {
        ok: false,
        code: "invalid_input",
        reason: `grant subject_id ${JSON.stringify(grant.subjectId)} is not a plain identifier`,
      };
    }
    if (grant.rights.length === 0) {
      return { ok: false, code: "invalid_input", reason: `grant for ${grant.subjectId} names no rights` };
    }
  }
  return { ok: true };
}

/**
 * Build the metadata file for a freshly initialised archive.
 * @param input - generated id, binding, grants and renderer.
 * @returns the metadata as it will be stored.
 */
export function initialMeta(input: {
  readonly archiveId: string;
  readonly binding: SourceBinding;
  readonly grants: readonly Grant[];
  readonly renderer: string;
}): ArchiveMeta {
  return {
    format: ARCHIVE_FORMAT,
    archiveId: input.archiveId,
    // The first published commit is sequence 1; the metadata records the
    // sequence it describes, not the commit that contains it.
    sequence: 1,
    binding: input.binding,
    grants: input.grants,
    renderer: input.renderer,
  };
}

/**
 * Parse the metadata file, refusing anything this code does not understand.
 *
 * An unknown `format` is refused rather than read leniently: a future archive
 * may put different meaning in the same keys, and guessing would corrupt it.
 * @param text - the file contents.
 * @returns the metadata, or a refusal.
 */
export function parseMeta(text: string): { ok: true; meta: ArchiveMeta } | ArchiveRefusal {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    return { ok: false, code: "invalid_input", reason: `meta.json is not valid JSON: ${(error as Error).message}` };
  }
  if (parsed === null || typeof parsed !== "object") {
    return { ok: false, code: "invalid_input", reason: "meta.json is not an object" };
  }
  const meta = parsed as Partial<ArchiveMeta>;
  if (meta.format !== ARCHIVE_FORMAT) {
    return {
      ok: false,
      code: "unknown_format",
      reason: `meta.json declares format ${JSON.stringify(meta.format ?? null)}, but this code reads ${ARCHIVE_FORMAT}`,
    };
  }
  if (typeof meta.archiveId !== "string" || !isSafeSegment(meta.archiveId)) {
    return { ok: false, code: "invalid_input", reason: "meta.json has no usable archive id" };
  }
  if (typeof meta.sequence !== "number" || !Number.isInteger(meta.sequence) || meta.sequence < 1) {
    return { ok: false, code: "invalid_input", reason: "meta.json has no usable sequence" };
  }
  if (meta.binding === undefined) {
    return { ok: false, code: "invalid_input", reason: "meta.json has no binding" };
  }
  return { ok: true, meta: meta as ArchiveMeta };
}

/**
 * Build one record envelope.
 *
 * The revision and sequences are passed in rather than computed here, because
 * the caller holds the lock that makes them true; this function only ensures
 * the shape is complete and that the kind is one this format defines.
 * @param input - the record's fields.
 * @returns the envelope, or a refusal for an unknown kind or unsafe id.
 */
export function recordEnvelope(input: {
  readonly kind: string;
  readonly id: string;
  readonly objectRevision: number;
  readonly createdSequence: number;
  readonly updatedSequence: number;
  readonly body: Readonly<Record<string, unknown>>;
}): { ok: true; record: RecordEnvelope } | ArchiveRefusal {
  if (!(RECORD_KINDS as readonly string[]).includes(input.kind)) {
    return {
      ok: false,
      code: "unknown_kind",
      reason: `record kind ${JSON.stringify(input.kind)} is not part of ${ARCHIVE_FORMAT} (${RECORD_KINDS.join(", ")})`,
    };
  }
  if (!isSafeSegment(input.id)) {
    return { ok: false, code: "invalid_input", reason: `record id ${JSON.stringify(input.id)} is not a plain identifier` };
  }
  if (input.objectRevision < 1) {
    return { ok: false, code: "invalid_input", reason: "object_revision must be at least 1" };
  }
  if (input.createdSequence < 1 || input.updatedSequence < input.createdSequence) {
    return {
      ok: false,
      code: "invalid_input",
      reason: "created_sequence and updated_sequence must be ordered positive integers",
    };
  }
  return {
    ok: true,
    record: {
      format: ARCHIVE_FORMAT,
      kind: input.kind as RecordKind,
      id: input.id,
      objectRevision: input.objectRevision,
      createdSequence: input.createdSequence,
      updatedSequence: input.updatedSequence,
      body: input.body,
    },
  };
}

/**
 * Parse a stored record, refusing an unknown format or kind.
 * @param text - the file contents.
 * @returns the record, or a refusal.
 */
export function parseRecord(text: string): { ok: true; record: RecordEnvelope } | ArchiveRefusal {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    return { ok: false, code: "invalid_input", reason: `record is not valid JSON: ${(error as Error).message}` };
  }
  if (parsed === null || typeof parsed !== "object") {
    return { ok: false, code: "invalid_input", reason: "record is not an object" };
  }
  const record = parsed as Partial<RecordEnvelope>;
  if (record.format !== ARCHIVE_FORMAT) {
    return {
      ok: false,
      code: "unknown_format",
      reason: `record declares format ${JSON.stringify(record.format ?? null)}, but this code reads ${ARCHIVE_FORMAT}`,
    };
  }
  if (!(RECORD_KINDS as readonly string[]).includes(String(record.kind))) {
    return {
      ok: false,
      code: "unknown_kind",
      reason: `record kind ${JSON.stringify(record.kind ?? null)} is not part of ${ARCHIVE_FORMAT}`,
    };
  }
  return { ok: true, record: record as RecordEnvelope };
}

/**
 * Build the operation record for one published commit.
 * @param input - sequence, derived actor, action, and what changed.
 * @returns the operation, with the payload reduced to its digest.
 */
export function operationRecord(input: {
  readonly sequence: number;
  readonly actor: string;
  readonly action: string;
  readonly payload: unknown;
  readonly changedIds: readonly string[];
  readonly result: Readonly<Record<string, unknown>>;
}): OperationRecord {
  return {
    format: ARCHIVE_FORMAT,
    sequence: input.sequence,
    actor: input.actor,
    action: input.action,
    payloadDigest: digestOf(canonicalJson(input.payload)),
    changedIds: input.changedIds,
    result: input.result,
  };
}

/**
 * Build the receipt for one operation key.
 *
 * The receipt stores the *sequence* the key first published at, never the hash
 * of the commit that contained it: that hash depends on the tree that contains
 * the receipt, which would be circular.
 * @param input - payload digest, sequence and result.
 * @returns the receipt as it will be stored.
 */
export function receiptRecord(input: {
  readonly payloadDigest: string;
  readonly sequence: number;
  readonly result: Readonly<Record<string, unknown>>;
}): ReceiptRecord {
  return {
    format: ARCHIVE_FORMAT,
    payloadDigest: input.payloadDigest,
    sequence: input.sequence,
    result: input.result,
  };
}

/**
 * Decide what a retry of the same operation key means.
 *
 * `COMMANDS.md` §6 fixes the order: authorization first (the caller does that),
 * then the receipt, then the expected revision. So a receipt hit is answered
 * before any revision comparison, which is what makes a lost response retryable
 * with a stale revision.
 *
 * A same key with a *different* payload is refused rather than answered: the
 * key identifies one operation, and silently returning a different operation's
 * result would be a lie about what was committed.
 * @param existing - the stored receipt, when the key was used before.
 * @param payloadDigest - the digest of the payload now being sent.
 * @returns what the caller should do.
 */
export function judgeRetry(
  existing: ReceiptRecord | undefined,
  payloadDigest: string,
): { readonly kind: "new" } | { readonly kind: "replay"; readonly receipt: ReceiptRecord } | ArchiveRefusal {
  if (existing === undefined) return { kind: "new" };
  if (existing.payloadDigest === payloadDigest) return { kind: "replay", receipt: existing };
  return {
    ok: false,
    code: "invalid_input",
    reason: `operation key was already used for a different payload (${existing.payloadDigest} != ${payloadDigest}); refusing to report another operation's result`,
  };
}

/**
 * Check that a caller-supplied `expected_revision` is usable.
 *
 * `absent` is accepted only when the caller says this is the first write, which
 * is how owner `initialize` works. A model-facing write never gets to use it,
 * because that would let a caller create an archive it was not authorised to
 * create; that rule lives in the caller, and this function only refuses the
 * shapes that are invalid for everyone.
 * @param expected - the caller's value.
 * @param options.allowAbsent - whether this call may be a first write.
 * @returns a refusal, or the normalised expectation.
 */
export function validateExpectedRevision(
  expected: unknown,
  options: { readonly allowAbsent: boolean },
): { ok: true; expected: string | null } | ArchiveRefusal {
  if (expected === "absent") {
    if (!options.allowAbsent) {
      return {
        ok: false,
        code: "invalid_input",
        reason: "expected_revision absent is only valid for the owner's first initialisation",
      };
    }
    return { ok: true, expected: null };
  }
  if (typeof expected !== "string" || expected.trim() === "") {
    return { ok: false, code: "invalid_input", reason: "expected_revision must be a commit id or absent" };
  }
  if (expected === "latest" || expected === "HEAD") {
    return {
      ok: false,
      code: "invalid_input",
      reason: `expected_revision ${JSON.stringify(expected)} is not a revision; pass the commit id you read`,
    };
  }
  if (!/^[0-9a-f]{40}$/.test(expected)) {
    return { ok: false, code: "invalid_input", reason: "expected_revision must be a 40-character commit id" };
  }
  return { ok: true, expected };
}
